import type { CompetencyId, ExerciseEntry } from '@/lib/learning-types';
import type { CalculationExercise, Exercise, SkillId, Unit } from '@/lib/types';

type Draft = Exercise extends infer E
  ? E extends Exercise
    ? Omit<E, 'skills' | 'competencyIds' | 'difficulty' | 'templateId' | 'variantId' | 'seed'>
    : never
  : never;

function make(
  lessonId: string,
  competencyIds: CompetencyId[],
  difficulty: 1 | 2 | 3,
  draft: Draft,
): ExerciseEntry {
  const skills = new Set<SkillId>();
  for (const competency of competencyIds) {
    if (['financial-literacy', 'interest-rates', 'inflation'].includes(competency))
      skills.add('literacy');
    if (
      [
        'interest-rates',
        'inflation',
        'returns',
        'compounding',
        'present-value',
        'future-value',
        'discounting',
        'npv',
        'irr',
        'portfolio-returns',
      ].includes(competency)
    )
      skills.add('mathematics');
    if (
      ['returns', 'stocks', 'bonds', 'dividends', 'risk-return', 'npv', 'irr'].includes(competency)
    )
      skills.add('investments');
    if (['portfolio-returns', 'diversification', 'risk-return'].includes(competency))
      skills.add('portfolio');
  }
  return {
    lessonId,
    competencyIds,
    difficulty,
    exercise: {
      ...draft,
      skills: [...skills],
      competencyIds,
      difficulty,
      templateId: draft.id,
      variantId: `${draft.id}:v1`,
      seed: 0,
    } as Exercise,
  };
}
function n(
  id: string,
  prompt: string,
  expected: number,
  unit: Unit,
  hint: string,
  explanation: string,
): Draft {
  return {
    id,
    kind: 'numeric',
    prompt,
    expected,
    unit,
    ...(unit === 'currency' ? { currency: 'RUB' as const } : {}),
    absoluteTolerance: 0.005,
    hint,
    explanation,
    instruction:
      unit === 'percent'
        ? 'Введите число процентов, например 7,5. Ответ округлите до сотых.'
        : unit === 'currency'
          ? 'Ответ в рублях. Округлите до копеек.'
          : 'Введите число. Если требуется округление, используйте две цифры после запятой.',
  };
}
function c(
  id: string,
  prompt: string,
  labels: string[],
  answers: number | number[],
  hint: string,
  explanation: string,
  scenario = false,
): Draft {
  const correct = Array.isArray(answers) ? answers : [answers];
  return {
    id,
    kind: scenario ? 'scenario' : 'choice',
    prompt,
    options: labels.map((label, index) => ({ id: String(index), label })),
    correct: correct.map(String),
    multiple: Array.isArray(answers),
    hint,
    explanation,
    instruction: Array.isArray(answers)
      ? 'Выберите все верные варианты.'
      : 'Выберите один обоснованный ответ.',
  };
}
function b(id: string, prompt: string, correct: boolean, hint: string, explanation: string): Draft {
  return {
    id,
    kind: 'boolean',
    prompt,
    correct,
    hint,
    explanation,
    instruction: 'Определите, верно ли утверждение при указанных условиях.',
  };
}
function m(
  id: string,
  prompt: string,
  pairs: [string, string][],
  hint: string,
  explanation: string,
): Draft {
  return {
    id,
    kind: 'matching',
    prompt,
    pairs: pairs.map(([left, right], index) => ({ id: String(index), left, right })),
    hint,
    explanation,
    instruction: 'Каждому элементу слева назначьте отдельное соответствие.',
  };
}
function o(id: string, prompt: string, labels: string[], hint: string, explanation: string): Draft {
  return {
    id,
    kind: 'ordering',
    prompt,
    items: labels.map((label, index) => ({ id: String(index), label })),
    correctOrder: labels.map((_, index) => String(index)),
    hint,
    explanation,
    instruction: 'Расположите этапы в логической последовательности от первого к последнему.',
  };
}
function calc(
  id: string,
  prompt: string,
  model: CalculationExercise['model'],
  parameters: CalculationExercise['parameters'],
  unit: Unit,
  hint: string,
  explanation: string,
): Draft {
  return {
    id,
    kind: 'calculation',
    prompt,
    model,
    parameters,
    unit,
    ...(unit === 'currency' ? { currency: 'RUB' as const } : {}),
    absoluteTolerance: 0.005,
    hint,
    explanation,
    instruction:
      'Можно изменить параметры. Рассчитайте ответ для текущих значений. Ставки задаются числом процентов, денежные суммы — рублями; результат округлите до сотых.',
  };
}

